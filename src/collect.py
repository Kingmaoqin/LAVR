"""
Phase 0A -- oracle label collection.

Walk trajectories generated by pi_ref, snapshot states s_t, and at each snapshot
estimate the policy-relative advantage A^{pi_ref}(i | s_t) of committing
(i, x_hat_i) by CRN-coupled paired rollouts. Nothing here trains; the backbone
is frozen and no gradient is taken through a rollout.

Every stored label is POLICY-RELATIVE: it is A^{pi_ref}, never A*.

FROZEN before any probe was fitted, chosen from a pilot that
measured label signal-to-noise, NOT from probe results:
  pi_ref    ancestral uniform-random-order unmasking, 1 commit/step,
            top_k=50, temperature 1.0                      (see policy.py)
  G         Rao-Blackwellised Path-LL. The realised-token estimator was
            measured to have SNR 0.1-0.6 at this scale -- its rollout noise
            EXCEEDS the between-candidate signal, so it cannot support any
            conclusion. The Rao-Blackwellised estimator reaches SNR 2-4.
  horizon   H = 16 pi_ref commits scored after the decision point. Longer
            horizons dilute a single token's effect across more future
            randomness (measured SNR falls to ~1 at H=None).
  K         24 CRN-coupled paired rollouts per branch. K=8 left the
            downstream-only label A_future at SNR 0.74 (ancestral) / 0.59
            (confidence) -- below 1, so its null was uninformative rather than
            evidence of absence. Noise falls as 1/K; K=24 lifts A_future to a
            projected SNR of ~2.2 / ~1.8 and its R^2 ceiling from 0.43 to ~0.69.
  labels    A_full   = advantage of the per-token Path-LL INCLUDING the forced
                       action's own log-probability (literal POKE Path-LL)
            A_future = the action's downstream effect only. Harder, because the
                       action's own log-probability IS a cheap control feature.
            Both are reported; both were pre-registered.
"""
import os
